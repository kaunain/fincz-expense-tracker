#!/usr/bin/env node
/**
 * @file scripts/set-build-date.js
 * @description Prebuild script that stamps the current date/time into build-info.ts.
 *
 * Why: The old code used `new Date()` inside build-info.ts which evaluates at
 * RUNTIME (every page reload), not at build time. This script runs ONCE before
 * the Angular build and writes a static date string into the file.
 *
 * Usage: Automatically called by the "prebuild" npm/pnpm lifecycle hook.
 *        You can also run it manually: node scripts/set-build-date.js
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Resolve path to build-info.ts relative to this script
const buildInfoPath = resolve(__dirname, '../src/app/core/config/build-info.ts');

// Read version from package.json
const pkg = JSON.parse(readFileSync(resolve(__dirname, '../package.json'), 'utf8'));
const appVersion = `v${pkg.version}`;

// Get current git commit hash (short) and branch — fallback gracefully if git is unavailable
let commitHash = 'unknown';
let gitBranch = 'unknown';
try {
  commitHash = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
  gitBranch = execSync('git rev-parse --abbrev-ref HEAD', { encoding: 'utf8' }).trim();
} catch {
  // Git not available (e.g. in CI without full clone) — use fallback values
  console.warn('[set-build-date] Warning: Could not read git info, using fallback values.');
}

// Format current date as a human-readable string (e.g. "2 Aug 2026, 10:15 AM")
const now = new Date();
const lastBuildDate = now.toLocaleString('en-IN', {
  year: 'numeric',
  month: 'short',
  day: 'numeric',
  hour: '2-digit',
  minute: '2-digit',
  hour12: true,
  timeZone: 'Asia/Kolkata',
});

// Write the updated build-info.ts with static values (no runtime Date() calls)
const content = `/**
 * @file build-info.ts
 * @description Build-time stamped version and metadata.
 *
 * AUTO-GENERATED by scripts/set-build-date.js — do NOT edit manually.
 * This file is updated automatically before every \`pnpm run build\`.
 */

export interface BuildInfo {
  appVersion: string;
  gitBranch: string;
  commitHash: string;
  /** Static date string set at build time — does NOT change on page reload */
  lastBuildDate: string;
}

export const BUILD_INFO: BuildInfo = {
  appVersion: '${appVersion}',
  gitBranch: '${gitBranch}',
  commitHash: '${commitHash}',
  lastBuildDate: '${lastBuildDate}',
};
`;

writeFileSync(buildInfoPath, content, 'utf8');
console.log(
  `[set-build-date] ✅ Build info updated: ${appVersion} @ ${lastBuildDate} (${commitHash})`
);
